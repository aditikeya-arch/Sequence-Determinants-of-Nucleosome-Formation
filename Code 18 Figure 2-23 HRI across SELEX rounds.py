

"""
Code 18 Figure 2-23 HRI across SELEX rounds.py
===============================================

WHAT THIS SCRIPT DOES
---------------------
Generates the data underlying Figure 2.23.

For each of the six SELEX rounds:

    1. Select the 10,000 sequences with the highest
       Counts Per Million.

    2. Remove near-duplicate sequences differing at
       fewer than 10 positions, retaining the more
       abundant sequence.

    3. Calculate the Helical Repetition Index (HRI)
       matrix for all 136 unordered NN-NN pairs.

Figure 2.23a consists of the six resulting HRI matrices.

For Figure 2.23b, three cumulative HRI signals are
calculated from each matrix:

    WW-WW:
        sum of the 10 independent HRI values formed
        by the four WW dinucleotides

    SS-SS:
        sum of the 10 independent HRI values formed
        by the four SS dinucleotides

    WW-SS:
        sum of all 16 HRI values formed by one WW
        and one SS dinucleotide

The three trajectories are also normalized relative to
their respective Round 6 magnitudes.


WW AND SS DEFINITIONS
---------------------
WW:

    AA
    AT
    TA
    TT

SS:

    CC
    CG
    GC
    GG


INPUT FILES
-----------
R1.csv
R2.csv
R3.csv
R4.csv
R5.csv
R6.csv

Each file must contain:

    Sequence
    Counts Per Million


VARIABLES / FUNCTIONS THAT MUST ALREADY EXIST
---------------------------------------------
The following functions and variables are generated by:

    Code 17 Figure 2-22 HRI heatmaps.py

Required:

    filter_top_sequences
    compute_hri_matrix
    DINUCLEOTIDE_ORDER


OTHER SCRIPTS THAT MUST BE RUN FIRST
------------------------------------
Code 17 Figure 2-22 HRI heatmaps.py


OUTPUTS
-------
HRI_by_round

    Dictionary containing the labelled 16 x 16 HRI
    matrix for each SELEX round.


figure_2_23a

    Long-format DataFrame containing the HRI matrices
    for all six rounds.


figure_2_23b

    DataFrame containing:

        Round
        WW_WW
        SS_SS
        WW_SS
        WW_WW_normalized
        SS_SS_normalized
        WW_SS_normalized


No plotting is performed.
"""


