# ============================================================
# 10. Normalize each trajectory to its Round 6 magnitude
# ============================================================

round_6 = (

    figure_2_23b

    .loc[
        figure_2_23b[
            "Round"
        ] == 6
    ]

    .iloc[0]
)


for category in [

    "WW_WW",

    "SS_SS",

    "WW_SS",
]:

    round_6_magnitude = abs(

        round_6[
            category
        ]
    )


    if (
        round_6_magnitude
        ==
        0
    ):

        figure_2_23b[

            category
            +
            "_normalized"

        ] = np.nan


    else:

        figure_2_23b[

            category
            +
            "_normalized"

        ] = (

            figure_2_23b[
                category
            ]

            /

            round_6_magnitude
        )


