# ============================================================
# 8. Independent within-class pairs
# ============================================================

def independent_pairs(
    dinucleotides
):

    """
    Return the independent unordered pairs formed from
    a set of dinucleotides, including the diagonal.

    Four dinucleotides therefore give:

        4 diagonal entries
        +
        6 off-diagonal entries
        =
        10 independent entries.
    """

    pairs = []


    for i in range(
        len(
            dinucleotides
        )
    ):

        for j in range(
            i,
            len(
                dinucleotides
            )
        ):

            pairs.append(

                (
                    dinucleotides[i],
                    dinucleotides[j]
                )
            )


    return pairs


WW_WW_PAIRS = independent_pairs(
    WW
)


SS_SS_PAIRS = independent_pairs(
    SS
)


# WW-SS contains all 4 x 4 combinations.

WW_SS_PAIRS = [

    (
        ww,
        ss
    )

    for ww in WW

    for ss in SS
]


assert len(
    WW_WW_PAIRS
) == 10


assert len(
    SS_SS_PAIRS
) == 10


assert len(
    WW_SS_PAIRS
) == 16


# ============================================================
# 9. Sum the three HRI classes
# ============================================================

def sum_hri_pairs(
    matrix,
    pairs
):

    """
    Sum the specified independent entries from a
    symmetric HRI matrix.

    Each unordered pair is counted once.
    """

    return sum(

        matrix.loc[
            dinucleotide_1,
            dinucleotide_2
        ]

        for (
            dinucleotide_1,
            dinucleotide_2
        )

        in pairs
    )


