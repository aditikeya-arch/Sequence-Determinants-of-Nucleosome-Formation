def load_round(
    filename
):

    """
    Load one SELEX CSV and check the required columns.
    """

    dataframe = pd.read_csv(
        filename
    )


    required_columns = {

        "Sequence",

        "Counts Per Million",
    }


    missing_columns = (

        required_columns

        -

        set(
            dataframe.columns
        )
    )


    if missing_columns:

        raise ValueError(

            f"{filename} is missing columns: "
            f"{missing_columns}"
        )


    dataframe[
        "Sequence"
    ] = (

        dataframe[
            "Sequence"
        ]

        .astype(str)

        .str.upper()
    )


    return dataframe


