# 10. Individual-sequence rho(d)
# ============================================================

def individual_rho(
    sequence,
    dinucleotide_1,
    dinucleotide_2
):

    """
    Calculate rho(d) for one 113-bp sequence.

    This follows the individual-sequence HRI approach
    used in Code 19.
    """

    rho = np.full(
        112,
        np.nan
    )


    for distance in range(
        1,
        112
    ):

        observed = 0


        for i in range(
            N_DINUCLEOTIDE_STARTS
            -
            distance
        ):

            left = sequence[
                i:
                i + 2
            ]

            right = sequence[
                i + distance:
                i + distance + 2
            ]


            if dinucleotide_1 == dinucleotide_2:

                if (

                    left == dinucleotide_1

                    and

                    right == dinucleotide_2

                ):

                    observed += 1


            else:

                if (

                    (
                        left == dinucleotide_1
                        and
                        right == dinucleotide_2
                    )

                    or

                    (
                        left == dinucleotide_2
                        and
                        right == dinucleotide_1
                    )

                ):

                    observed += 1


        if dinucleotide_1 == dinucleotide_2:

            expected = (

                (
                    N_DINUCLEOTIDE_STARTS
                    -
                    distance
                )

                /

                256
            )

        else:

            expected = (

                (
                    N_DINUCLEOTIDE_STARTS
                    -
                    distance
                )

                /

                128
            )


        rho[
            distance
        ] = (

            observed

            /

            expected
        )


    return rho


# ============================================================
# 11. Individual HRI
# ============================================================

def individual_hri(
    sequence,
    dinucleotide_1,
    dinucleotide_2
):

    rho = individual_rho(

        sequence,

        dinucleotide_1,

        dinucleotide_2
    )


    return hri_from_rho(
        rho
    )


