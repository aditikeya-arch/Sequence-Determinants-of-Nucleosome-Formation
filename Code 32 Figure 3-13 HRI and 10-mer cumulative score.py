# 5. Pair-count helper
# ============================================================

def count_pair_at_distance(
    sequences,
    dinucleotide_1,
    dinucleotide_2,
    distance
):

    """
    Count occurrences of an unordered dinucleotide pair
    separated by a given distance between dinucleotide
    start positions.

    For identical dinucleotides, each occurrence is
    counted once.

    For different dinucleotides, both orientations are
    included:

        NN1 ... NN2
        NN2 ... NN1
    """

    count = 0


    for sequence in sequences:

        for i in range(
            N_DINUCLEOTIDE_STARTS
            -
            distance
        ):

            left = sequence[
                i:
                i + 2
            ]

            right = sequence[
                i + distance:
                i + distance + 2
            ]


            if dinucleotide_1 == dinucleotide_2:

                if (
                    left == dinucleotide_1
                    and
                    right == dinucleotide_2
                ):

                    count += 1

            else:

                if (

                    (
                        left == dinucleotide_1
                        and
                        right == dinucleotide_2
                    )

                    or

                    (
                        left == dinucleotide_2
                        and
                        right == dinucleotide_1
                    )

                ):

                    count += 1


    return count


# ============================================================
# 6. Pooled rho(d)
# ============================================================

def pooled_rho(
    sequences,
    dinucleotide_1,
    dinucleotide_2
):

    """
    Calculate rho(d) across a pooled group of sequences.

    This follows the pooled HRI calculation used for the
    Figure 2.22 heatmaps.
    """

    N = len(
        sequences
    )


    rho = np.full(
        112,
        np.nan
    )


    for distance in range(
        1,
        112
    ):

        observed = count_pair_at_distance(

            sequences,

            dinucleotide_1,

            dinucleotide_2,

            distance
        )


        if dinucleotide_1 == dinucleotide_2:

            expected = (

                N

                *

                (
                    N_DINUCLEOTIDE_STARTS
                    -
                    distance
                )

                /

                256
            )

        else:

            expected = (

                N

                *

                (
                    N_DINUCLEOTIDE_STARTS
                    -
                    distance
                )

                /

                128
            )


        rho[
            distance
        ] = (

            observed

            /

            expected
        )


    return rho


# ============================================================
# 7. Convert rho(d) into HRI
# ============================================================

def hri_from_rho(
    rho
):

    """
    HRI = sum of maxima around integer helical repeats
          minus
          sum of maxima around half-integer repeats.

    Each maximum is taken within +/- 1 bp of the nominal
    centre.
    """

    full_values = []

    half_values = []


    for centre in FULL_HELICAL_CENTRES:

        values = rho[
            centre - 1:
            centre + 2
        ]


        full_values.append(
            np.nanmax(values)
        )


    for centre in HALF_HELICAL_CENTRES:

        values = rho[
            centre - 1:
            centre + 2
        ]


        half_values.append(
            np.nanmax(values)
        )


    return (

        np.sum(
            full_values
        )

        -

        np.sum(
            half_values
        )
    )


# ============================================================
# 8. Calculate one pooled HRI matrix
# ============================================================

def calculate_pooled_hri_matrix(
    sequences
):

    """
    Calculate the symmetric 16 x 16 pooled HRI matrix.
    """

    matrix = np.full(
        (16, 16),
        np.nan
    )


    for i, dinucleotide_1 in enumerate(
        DINUCLEOTIDE_ORDER
    ):

        for j in range(
            i,
            16
        ):

            dinucleotide_2 = (
                DINUCLEOTIDE_ORDER[j]
            )


            rho = pooled_rho(

                sequences,

                dinucleotide_1,

                dinucleotide_2
            )


            hri = hri_from_rho(
                rho
            )


            matrix[
                i,
                j
            ] = hri


            matrix[
                j,
                i
            ] = hri


    return matrix


