

"""
Code 32 Figure 3-13 HRI and 10-mer cumulative score.py
=======================================================

WHAT THIS SCRIPT DOES
---------------------
Generates the data underlying Figure 3.13.

FIGURE 3.13a
------------
HRI heatmaps are calculated for:

    1. 10,000 sequences with the lowest 10-mer
       cumulative scores

    2. 10,000 randomly selected sequences

    3. 10,000 sequences with the highest 10-mer
       cumulative scores

The pooled-sequence HRI calculation follows:

    Code 17 Figure 2-22 HRI heatmaps.py


FIGURE 3.13b
------------
For each of the 100,000 random sequences, individual-
sequence HRI values are calculated.

The individual-sequence calculation follows the same
approach used in:

    Code 19 Figure 2-24 HRI contribution to intrinsic
    cyclisability.py

Three quantities are then calculated:

    Sum of 10 independent WW-WW HRI values
    Sum of 10 independent SS-SS HRI values
    Sum of 16 independent WW-SS HRI values

These are compared with the 10-mer cumulative score.


FIGURE 3.13c
------------
For every reverse-complement-collapsed 10-mer in the
SELEX enrichment table, the number of WW-SS dinucleotide
pairs separated by 4, 5 or 6 bp is calculated.

This is compared with the corresponding R6 versus R1
log2 enrichment value.


VARIABLES THAT MUST ALREADY EXIST
---------------------------------
random_sequences

    100,000 random 147-bp sequences generated by:

        Code 31 Figures 3-11 and 3-12 10-mer cumulative
        score sequence properties.py


tenmer_cumulative_score

    108-bp 10-mer cumulative score for those same
    100,000 sequences.

    Generated by Code 31.


df_enrichment_rc

    Reverse-complement-collapsed 10-mer enrichment table.

    Generated by:

        Code 20 Figure 2-25a 10-mer enrichment
        distribution.py


OTHER SCRIPTS THAT MUST BE RUN FIRST
------------------------------------
1. Code 20 Figure 2-25a 10-mer enrichment distribution.py

2. Code 31 Figures 3-11 and 3-12 10-mer cumulative
   score sequence properties.py


OUTPUTS
-------
figure_3_13a_HRI_matrices

    Dictionary containing HRI matrices for:

        Lowest
        Random
        Highest


figure_3_13b

    Individual-sequence data containing:

        10-mer cumulative score
        WW-WW HRI sum
        SS-SS HRI sum
        WW-SS HRI sum


figure_3_13b_correlations

    Pearson correlations with 10-mer cumulative score.


figure_3_13c

    Reverse-complement-collapsed 10-mer enrichment and
    number of WW-SS pairs separated by 4, 5 or 6 bp.


figure_3_13c_correlation

    Pearson correlation for Figure 3.13c.


NOTES
-----
No plotting is performed.
"""


