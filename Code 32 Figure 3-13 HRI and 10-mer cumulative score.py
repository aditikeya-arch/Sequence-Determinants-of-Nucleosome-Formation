# 15. Figure 3.13b correlations
# ============================================================

def correlation(
    x,
    y
):

    x = np.asarray(
        x,
        dtype=float
    )

    y = np.asarray(
        y,
        dtype=float
    )


    valid = (

        np.isfinite(x)

        &

        np.isfinite(y)
    )


    r, p = pearsonr(

        x[valid],

        y[valid]
    )


    return (
        int(valid.sum()),
        r,
        p
    )


