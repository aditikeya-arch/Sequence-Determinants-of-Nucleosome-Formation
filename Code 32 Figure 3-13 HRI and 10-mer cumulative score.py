# 16. Count WW-SS pairs in a 10-mer
# ============================================================

def count_ww_ss_pairs_4_to_6(
    kmer
):

    """
    Count WW-SS dinucleotide pairs whose dinucleotide
    start positions are separated by 4, 5 or 6 bp.

    Both orientations are included:

        WW ... SS

        SS ... WW
    """

    assert len(
        kmer
    ) == 10


    dinucleotides = [

        kmer[
            i:
            i + 2
        ]

        for i in range(9)
    ]


    count = 0


    for distance in [
        4,
        5,
        6
    ]:

        for i in range(
            9 - distance
        ):

            first = (
                dinucleotides[i]
            )

            second = (
                dinucleotides[
                    i + distance
                ]
            )


            if (

                (
                    first in WW
                    and
                    second in SS
                )

                or

                (
                    first in SS
                    and
                    second in WW
                )

            ):

                count += 1


    return count


