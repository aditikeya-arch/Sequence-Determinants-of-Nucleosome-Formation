# ============================================================
# 10. Extract central 113 bp
# ============================================================

def central_113_sequences(
    sequences
):

    """
    Extract the central 113-bp variable region from
    valid 147-bp sequences.
    """

    output = []


    for sequence in sequences:

        sequence = str(
            sequence
        ).upper()


        if len(
            sequence
        ) != RAW_LENGTH:

            continue


        core = sequence[
            TRIM:
            RAW_LENGTH - TRIM
        ]


        if (
            len(core) == SEQ_LEN

            and

            set(core) <= VALID_BASES
        ):

            output.append(
                core
            )


    return output


# ============================================================
# 11. Exact normalization constants
# ============================================================

# M[pair, distance] is the expected number of occurrences
# in one random 113-bp sequence at that separation.
#
# Identical pair:
#
#     (112 - d) / 256
#
# Different unordered pair:
#
#     (112 - d) / 128

M = np.zeros(
    (
        len(PAIRS),
        len(DISTS)
    ),
    dtype=float
)


for pair_index, (
    dinucleotide_1,
    dinucleotide_2
) in enumerate(
    PAIRS
):

    if (
        dinucleotide_1
        ==
        dinucleotide_2
    ):

        denominator = 256.0


    else:

        denominator = 128.0


    M[
        pair_index,
        :
    ] = (

        DINUC_STARTS

        -

        DISTS

    ) / denominator


# ============================================================
# 12. Convert one sequence to dinucleotide bit masks
# ============================================================

def sequence_to_masks(
    sequence
):

    """
    Encode the start positions of each of the 16
    dinucleotides as integer bit masks.

    Bit p is 1 when the corresponding dinucleotide
    starts at position p.
    """

    sequence_bytes = (
        sequence.encode(
            "ascii"
        )
    )


    masks = [
        0
    ] * 16


    for position in range(
        DINUC_STARTS
    ):

        code = (

            BASE_MAP[
                sequence_bytes[
                    position
                ]
            ]

            << 2

        ) | BASE_MAP[
            sequence_bytes[
                position + 1
            ]
        ]


        masks[
            code
        ] |= (
            1
            <<
            position
        )


    return masks


# ============================================================
# 13. Calculate one HRI matrix
# ============================================================

def compute_hri_matrix(
    full_sequences
):

    """
    Calculate the 16 x 16 symmetric HRI matrix for
    one sequence set.

    Pair counts are pooled across the entire sequence
    group before normalization.
    """

    sequences = central_113_sequences(
        full_sequences
    )


    total_counts = np.zeros(
        (
            len(PAIRS),
            len(DISTS)
        ),
        dtype=float
    )


    n_used = 0


    # --------------------------------------------------------
    # Accumulate pair counts
    # --------------------------------------------------------

    for sequence in sequences:

        masks = sequence_to_masks(
            sequence
        )


        for distance_index, distance in enumerate(
            DISTS
        ):

            shifted_masks = [

                mask
                >>
                int(distance)

                for mask in masks
            ]


            for pair_index, (
                dinucleotide_1,
                dinucleotide_2
            ) in enumerate(
                PAIRS
            ):


                # Identical pair.

                if (
                    dinucleotide_1
                    ==
                    dinucleotide_2
                ):

                    count = (

                        masks[
                            dinucleotide_1
                        ]

                        &

                        shifted_masks[
                            dinucleotide_1
                        ]

                    ).bit_count()


                # Different unordered pair:
                # count both orientations.

                else:

                    count = (

                        (
                            masks[
                                dinucleotide_1
                            ]

                            &

                            shifted_masks[
                                dinucleotide_2
                            ]

                        ).bit_count()

                        +

                        (
                            masks[
                                dinucleotide_2
                            ]

                            &

                            shifted_masks[
                                dinucleotide_1
                            ]

                        ).bit_count()
                    )


                total_counts[
                    pair_index,
                    distance_index
                ] += count


        n_used += 1


    print(
        "Sequences used:",
        n_used
    )


    if n_used == 0:

        raise ValueError(
            "No valid sequences were available for "
            "HRI calculation."
        )


    # --------------------------------------------------------
    # Normalized pairwise distribution rho(d)
    # --------------------------------------------------------

    rho = (

        total_counts

        /

        (
            n_used
            *
            M
        )
    )


    # --------------------------------------------------------
    # Calculate HRI
    # --------------------------------------------------------

    hri = np.zeros(
        len(PAIRS),
        dtype=float
    )


    # Add maxima around full-helical separations.

    for centre in HELIX:

        centre_index = np.where(
            DISTS == centre
        )[0][0]


        hri += np.max(

            rho[
                :,
                centre_index - 1:
                centre_index + 2
            ],

            axis=1
        )


    # Subtract maxima around half-helical separations.

    for centre in HALF:

        centre_index = np.where(
            DISTS == centre
        )[0][0]


        hri -= np.max(

            rho[
                :,
                centre_index - 1:
                centre_index + 2
            ],

            axis=1
        )


    # --------------------------------------------------------
    # Convert 136 HRI values into symmetric 16 x 16 matrix
    # --------------------------------------------------------

    hri_matrix = np.zeros(
        (
            16,
            16
        ),
        dtype=float
    )


    for value, (
        dinucleotide_1,
        dinucleotide_2
    ) in zip(
        hri,
        PAIRS
    ):

        hri_matrix[
            dinucleotide_1,
            dinucleotide_2
        ] = value


        hri_matrix[
            dinucleotide_2,
            dinucleotide_1
        ] = value


    # --------------------------------------------------------
    # Reorder for Figure 2.22
    # --------------------------------------------------------

    hri_matrix_ordered = (

        hri_matrix[
            np.ix_(
                ORDER_INDEX,
                ORDER_INDEX
            )
        ]
    )


    return (
        hri_matrix_ordered,
        rho,
        n_used
    )


