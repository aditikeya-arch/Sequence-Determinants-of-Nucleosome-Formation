def matrix_to_long(
    matrix,
    dataset
):

    """
    Convert a labelled HRI matrix to long format.
    """

    rows = []


    for row_dinucleotide in DINUCLEOTIDE_ORDER:

        for column_dinucleotide in DINUCLEOTIDE_ORDER:

            rows.append({

                "Dataset":
                    dataset,

                "Row_dinucleotide":
                    row_dinucleotide,

                "Column_dinucleotide":
                    column_dinucleotide,

                "HRI":
                    matrix.loc[
                        row_dinucleotide,
                        column_dinucleotide
                    ],
            })


    return pd.DataFrame(
        rows
    )


