

"""
Code 17 Figure 2-22 HRI heatmaps.py
====================================

WHAT THIS SCRIPT DOES
---------------------
Generates the data underlying Figure 2.22.

Figure 2.22 compares Helical Repetition Index (HRI)
matrices for four sequence groups:

    1. 9,803 randomly selected unique Round 1 sequences

    2. 9,803 most enriched Round 6 sequences

    3. 9,803 weakest-positioned native yeast nucleosomes

    4. 9,803 strongest-positioned native yeast nucleosomes


For every sequence, only the central 113-bp region is used.

A 113-bp sequence contains 112 possible dinucleotide
start positions.


PAIRWISE DISTRIBUTION
---------------------
For each unordered dinucleotide pair and separation d,
occurrences are pooled across the complete sequence set.

For identical dinucleotide pairs, the random expectation is:

    (112 - d) / 256

per sequence.

For non-identical unordered pairs, both orientations are
counted, giving:

    (112 - d) / 128

per sequence.

The normalized pairwise distribution is:

              observed pooled count
    rho(d) = -------------------------
              expected pooled count


HELICAL REPETITION INDEX
------------------------
The full-helical target separations are:

    10, 20, 30, ..., 110 bp

The half-helical target separations are:

    5, 15, 25, ..., 105 bp

For each target separation c, the maximum rho value within
the three-point interval:

    c - 1, c, c + 1

is used.

The HRI is then:

    HRI = sum(full-helical maxima)
          -
          sum(half-helical maxima)

Thus:

    positive HRI
        preference for full-helical-repeat spacing

    negative HRI
        preference for half-helical-repeat spacing


DINUCLEOTIDE PAIRS
------------------
All 136 unordered pairs of the 16 dinucleotides are
calculated.

The resulting matrix is symmetric because pair order is
not distinguished.


DINUCLEOTIDE ORDER
------------------
The heatmaps use:

    AA, AT, TA, TT,
    AC, AG, CA, CT, GA, GT, TC, TG,
    CC, CG, GC, GG

This places WW dinucleotides first, mixed dinucleotides
in the middle, and SS dinucleotides last.


INPUT FILES
-----------
R1.csv
R6.csv

Each CSV must contain:

    Sequence
    Counts Per Million


VARIABLES THAT MUST ALREADY EXIST
---------------------------------
native_nucleosomes

Generated by:

    Code 5 Native yeast nucleosomal sequences.py

Expected columns:

    Sequence
    NCP_score


OTHER SCRIPTS THAT MUST BE RUN FIRST
------------------------------------
Code 5 Native yeast nucleosomal sequences.py


ROUND 6 SEQUENCES
-----------------
The top 10,000 Round 6 sequences are initially selected
by Counts Per Million.

Near-duplicate sequences differing at fewer than 10
positions are removed, retaining the higher-abundance
sequence.

This gives 9,803 sequences.


ROUND 1 SEQUENCES
-----------------
9,803 unique valid Round 1 sequences are selected randomly.

The random seed is:

    42


NATIVE YEAST SEQUENCES
----------------------
Native nucleosomes are ranked by NCP score.

The 9,803 sequences with the lowest NCP scores are used
as the weakest-positioned nucleosomes.

The 9,803 sequences with the highest NCP scores are used
as the strongest-positioned nucleosomes.


OUTPUTS
-------
HRI_R1_random
HRI_R6_top
HRI_yeast_weak
HRI_yeast_strong

    16 x 16 DataFrames containing the HRI matrices.

figure_2_22

    Long-format DataFrame containing all four matrices.

No plotting is performed.
"""


