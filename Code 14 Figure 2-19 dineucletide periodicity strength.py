# ============================================================
# 6. Extract central 113-bp region
# ============================================================

def central_113(
    sequence
):

    """
    Extract positions 17:130 from a 147-bp sequence.
    """

    sequence = str(
        sequence
    ).upper()


    if len(
        sequence
    ) != RAW_LENGTH:

        raise ValueError(
            "Expected a 147-bp sequence, "
            f"but found length {len(sequence)}."
        )


    return sequence[
        TRIM:
        RAW_LENGTH - TRIM
    ]


# ============================================================
# 7. Construct dinucleotide indicator matrix
# ============================================================

def make_indicator_matrix(
    sequences,
    dinucleotide
):

    """
    Construct a matrix with one 113-element indicator
    trace per sequence.

    Positions 0-111 indicate whether the selected
    dinucleotide starts at that position.

    The final element remains zero.
    """

    N = len(
        sequences
    )


    indicator = np.zeros(
        (
            N,
            L
        ),
        dtype=np.float64
    )


    for sequence_index, sequence in enumerate(
        sequences
    ):

        sequence = central_113(
            sequence
        )


        for position in range(
            L - 1
        ):

            if (
                sequence[
                    position:
                    position + 2
                ]
                ==
                dinucleotide
            ):

                indicator[
                    sequence_index,
                    position
                ] = 1.0


    return indicator


# ============================================================
# 8. Calculate individual Fourier power spectra
# ============================================================

def calculate_power_spectra(
    sequences,
    dinucleotide
):

    """
    Calculate normalized Fourier power spectra for all
    sequences for one dinucleotide.
    """

    indicator = make_indicator_matrix(
        sequences,
        dinucleotide
    )


    # Mean-centre every sequence independently.

    centered = (

        indicator

        -

        indicator.mean(
            axis=1,
            keepdims=True
        )
    )


    # Hann window.

    hann_window = np.hanning(
        L
    ).astype(
        np.float64
    )


    window_power_correction = np.mean(
        hann_window ** 2
    )


    windowed = (

        centered

        *

        hann_window[
            None,
            :
        ]
    )


    # Real Fourier transform.

    fft_values = np.fft.rfft(
        windowed,
        axis=1
    )


    # Normalized power.

    power = (

        np.abs(
            fft_values
        ) ** 2

        /

        (
            L ** 2
            *
            window_power_correction
        )
    )


    # Exclude zero frequency.

    frequency_indices = np.arange(
        power.shape[1]
    )


    keep = (
        frequency_indices
        >
        0
    )


    frequency_indices = (
        frequency_indices[
            keep
        ]
    )


    periodicity = (

        L

        /

        frequency_indices
    )


    power = (
        power[
            :,
            keep
        ]
    )


    return (
        periodicity,
        power
    )


# ============================================================
# 9. Calculate mean power spectrum
# ============================================================

def mean_power_spectrum(
    sequences,
    dinucleotide,
    weights=None
):

    """
    Calculate the mean Fourier power spectrum.

    If weights is None, every sequence contributes equally.

    If weights are supplied, spectra are averaged using
    those weights.
    """

    periodicity, power = (
        calculate_power_spectra(
            sequences,
            dinucleotide
        )
    )


    if weights is None:

        mean_power = np.mean(
            power,
            axis=0
        )


    else:

        weights = np.asarray(
            weights,
            dtype=np.float64
        )


        if len(
            weights
        ) != len(
            sequences
        ):

            raise ValueError(
                "Number of weights does not match "
                "number of sequences."
            )


        mean_power = np.average(
            power,
            axis=0,
            weights=weights
        )


    return (
        periodicity,
        mean_power
    )


# ============================================================
# 10. Baseline correction and peak extraction
# ============================================================

def periodicity_peak(
    periodicity,
    mean_power
):

    """
    Restrict the spectrum to periodicities between
    5 and 20 bp.

    Calculate a Savitzky-Golay baseline and subtract it.

    Return the maximum baseline-corrected power and the
    periodicity at which that maximum occurs.
    """

    mask = (

        (periodicity >= PEAK_PERIOD_MIN)

        &

        (periodicity <= PEAK_PERIOD_MAX)
    )


    periodicity_selected = (
        periodicity[
            mask
        ]
    )


    power_selected = (
        mean_power[
            mask
        ]
    )


    if len(
        power_selected
    ) < BASELINE_WINDOW_LENGTH:

        raise ValueError(
            "Not enough Fourier points are present "
            "for the Savitzky-Golay baseline."
        )


    baseline = savgol_filter(

        power_selected,

        window_length=
            BASELINE_WINDOW_LENGTH,

        polyorder=
            BASELINE_POLYORDER
    )


    corrected_power = (

        power_selected

        -

        baseline
    )


    peak_index = np.argmax(
        corrected_power
    )


    peak_power = (
        corrected_power[
            peak_index
        ]
    )


    peak_periodicity = (
        periodicity_selected[
            peak_index
        ]
    )


    return (
        peak_power,
        peak_periodicity
    )


