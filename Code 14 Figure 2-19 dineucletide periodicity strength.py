

"""
Code 14 Figure 2-19 Dinucleotide periodicity strength.py
=========================================================

WHAT THIS SCRIPT DOES
---------------------
Generates the data underlying Figure 2.19.

The analysis quantifies periodicity strength for all 16
dinucleotides.

For each dinucleotide and each group of sequences:

    1. The central 113-bp variable region is retained.

    2. A dinucleotide indicator trace of length 113 is constructed:

           1 = the dinucleotide starts at this position
           0 = otherwise

       There are 112 possible dinucleotide start positions.
       Positions 0-111 contain the dinucleotide indicators and
       the final element remains 0.

    3. The mean of each individual indicator trace is subtracted.

    4. A Hann window of length 113 is applied.

    5. The real FFT (rFFT) is calculated.

    6. Power is calculated as the squared magnitude of the FFT.

    7. Power is normalized by:

           L^2 * mean(Hann_window^2)

       where L = 113.

    8. The zero-frequency component is excluded.

    9. Individual power spectra are averaged.

       For the top-sequence analyses, all retained sequences
       contribute equally.

       For analyses across all reads, spectra are weighted by
       Counts Per Million.

   10. To quantify the periodic signal, the mean spectrum is
       restricted to periodicities between 5 and 20 bp.

   11. A smooth baseline is calculated using a
       Savitzky-Golay filter with:

           window length = 9
           polynomial order = 2

   12. The baseline is subtracted from the mean spectrum.

   13. The maximum baseline-corrected power between 5 and
       20 bp is recorded as the periodicity strength.


FIGURE 2.19 OUTPUTS
-------------------
Panel 1:
    Peak periodic power for all 16 dinucleotides among the
    most enriched sequences in each SELEX round.

Panel 2:
    Peak periodic power for all 16 dinucleotides across all
    reads in each SELEX round, weighted by Counts Per Million.

Panel 3:
    Comparison of peak periodic power between the most
    enriched Round 6 SELEX sequences and the top 10% of
    native yeast nucleosomes.


INPUT FILES
-----------
R1.csv
R2.csv
R3.csv
R4.csv
R5.csv
R6.csv

Each SELEX CSV must contain:

    Sequence
    Counts Per Million


VARIABLES THAT MUST ALREADY EXIST
---------------------------------
native_nucleosomes

Generated by:

    Code 5 Native yeast nucleosomal sequences.py

Expected columns:

    Sequence
    NCP_score


OTHER SCRIPTS THAT MUST BE RUN FIRST
------------------------------------
Code 5 Native yeast nucleosomal sequences.py


TOP-SEQUENCE FILTERING
----------------------
For each SELEX round, sequences are ranked by
Counts Per Million.

The top 10,000 sequences are initially selected.

Near-duplicate sequences differing at fewer than 10 positions
are removed, retaining the higher-abundance sequence.


OUTPUTS
-------
figure_2_19_top

    Long-format dataframe containing peak periodicity
    strength for the top sequences in R1-R6.

figure_2_19_all

    Long-format dataframe containing peak periodicity
    strength across all reads in R1-R6, CPM weighted.

figure_2_19_native_comparison

    Long-format dataframe comparing Round 6 with the
    top 10% of native yeast nucleosomes.

Wide-format versions of all three outputs are also generated.

No plotting is performed.
"""


import numpy as np
import pandas as pd

from itertools import product
from scipy.signal import savgol_filter


# ============================================================
# 1. Analysis settings
# ============================================================

ROUNDS = [
    "R1",
    "R2",
    "R3",
    "R4",
    "R5",
    "R6",
]


DINUCLEOTIDES = [

    "".join(x)

    for x in product(
        "ACGT",
        repeat=2
    )
]


TOP_N = 10_000

MIN_HAMMING_DISTANCE = 10


# Full SELEX sequence length.

RAW_LENGTH = 147


# 17 bp are removed from each end.

TRIM = 17


# Length of the central variable region and Fourier trace.

L = 113


# Range used to identify the periodic peak.

PEAK_PERIOD_MIN = 5.0

PEAK_PERIOD_MAX = 20.0


# Savitzky-Golay baseline parameters.

BASELINE_WINDOW_LENGTH = 9

BASELINE_POLYORDER = 2


# ============================================================
# 2. Load SELEX rounds
# ============================================================

round_data = {}


for rnd in ROUNDS:

    filename = f"{rnd}.csv"


    df = pd.read_csv(
        filename
    )


    required_columns = {
        "Sequence",
        "Counts Per Million",
    }


    missing_columns = (

        required_columns

        -

        set(
            df.columns
        )
    )


    if missing_columns:

        raise ValueError(
            f"{filename} is missing columns: "
            f"{missing_columns}"
        )


    df["Sequence"] = (

        df["Sequence"]

        .astype(str)

        .str.upper()
    )


    # Check sequence lengths.

    sequence_lengths = (
        df["Sequence"]
        .str.len()
    )


    if not (
        sequence_lengths == RAW_LENGTH
    ).all():

        bad_lengths = (

            sequence_lengths[
                sequence_lengths != RAW_LENGTH
            ]

            .value_counts()

            .to_dict()
        )


        raise ValueError(
            f"{filename} contains sequences that are not "
            f"147 bp long: {bad_lengths}"
        )


    round_data[
        rnd
    ] = df


# ============================================================
# 3. Hamming distance
# ============================================================

def hamming_distance(
    sequence_1,
    sequence_2
):

    """
    Number of positions at which two equal-length
    sequences differ.
    """

    return sum(

        base_1 != base_2

        for base_1, base_2
        in zip(
            sequence_1,
            sequence_2
        )
    )


# ============================================================
# 4. Select and filter top sequences
# ============================================================

def filter_top_sequences(
    dataframe,
    top_n=TOP_N,
    min_distance=MIN_HAMMING_DISTANCE
):

    """
    Rank sequences by Counts Per Million and initially
    select the top N.

    Sequences are processed from highest to lowest
    abundance.

    A sequence is retained only if it differs from every
    previously retained sequence at at least
    `min_distance` positions.
    """

    top = (

        dataframe

        .sort_values(
            "Counts Per Million",
            ascending=False
        )

        .head(
            top_n
        )

        .reset_index(
            drop=True
        )
    )


    retained_rows = []

    retained_sequences = []


    for _, row in top.iterrows():

        sequence = row[
            "Sequence"
        ]


        keep = True


        for previous_sequence in retained_sequences:

            if hamming_distance(
                sequence,
                previous_sequence
            ) < min_distance:

                keep = False

                break


        if keep:

            retained_rows.append(
                row
            )

            retained_sequences.append(
                sequence
            )


    return (

        pd.DataFrame(
            retained_rows
        )

        .reset_index(
            drop=True
        )
    )


